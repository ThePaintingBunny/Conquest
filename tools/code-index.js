/*
 * Writes docs/CODE_INDEX.md and refreshes the "In this file:" list in every script's header.
 * Run with: npm run index
 *
 * The index lists every script with what it holds, and every top-level function and constant with the
 * file it lives in, so anything can be found by name.
 */
const fs = require('fs');
const path = require('path');
const { ROOT, SRC, scriptList, parseScript } = require('./scripts');

const WIDTH = 104;
const scripts = scriptList().map(parseScript);

/* "name()" for functions, "NAME" for constants and variables, in file order */
const labels = script => script.statements.flatMap(st => st.names.map(n => (st.isFunction ? n + '()' : n)));

function wrap(text, first, rest) {
  const lines = [];
  let line = first;
  text.split(/\s+/).forEach(word => {
    const empty = line === first || line === rest;
    if (!empty && (line + ' ' + word).length > WIDTH) {
      lines.push(line);
      line = rest + word;
    } else line += (empty ? '' : ' ') + word;
  });
  lines.push(line);
  return lines;
}

// ---- refresh the headers ----
let refreshed = 0;
scripts.forEach(script => {
  if (!script.header) return; // npm run check reports missing headers
  const names = labels(script);
  const kept = script.header
    .split('\n')
    .slice(0, -2) // drop " */" and the empty string after the final newline
    .join('\n')
    .replace(/\n \*\n \* In this file:[\s\S]*$/, '');
  const list = names.length ? '\n *\n' + wrap(names.join(', '), ' * In this file: ', ' *   ').join('\n') : '';
  const header = kept + list + '\n */\n';
  if (header !== script.header) {
    fs.writeFileSync(path.join(SRC, 'js', script.file), header + script.source.slice(script.header.length));
    refreshed++;
  }
});

// ---- write the index ----
const title = s => (s.header ? s.header.split('\n')[1].replace(/^ \* /, '') : '');
const summary = s => {
  if (!s.header) return '';
  const body = s.header.split('\n').slice(3, -2);
  const end = body.findIndex(l => l === ' *');
  return (end < 0 ? body : body.slice(0, end)).map(l => l.replace(/^ \* ?/, '')).join(' ');
};
const cell = t => t.replace(/\|/g, '\\|');

const out = [
  '# Code index',
  '',
  'Generated by `npm run index` from the scripts in `src/js`. Do not edit by hand.',
  '',
  '- [Files](#files): every script, grouped by folder, with what it holds.',
  '- [Names](#names): every top-level function and constant, A to Z, with its file.',
  '',
  '## Files',
  ''
];
const folders = new Map();
scripts.forEach(s => {
  const folder = s.file.includes('/') ? s.file.slice(0, s.file.lastIndexOf('/')) : '(top level)';
  if (!folders.has(folder)) folders.set(folder, []);
  folders.get(folder).push(s);
});
[...folders.keys()].sort().forEach(folder => {
  out.push(`### ${folder}`, '', '| File | What it holds |', '| --- | --- |');
  folders
    .get(folder)
    .sort((a, b) => a.file.localeCompare(b.file))
    .forEach(s => out.push(`| \`${s.file}\` | **${cell(title(s))}.** ${cell(summary(s))} |`));
  out.push('');
});
out.push('## Names', '', '| Name | File |', '| --- | --- |');
scripts
  .flatMap(s => s.statements.flatMap(st => st.names.map(n => [st.isFunction ? n + '()' : n, s.file])))
  .sort((a, b) => a[0].toLowerCase().localeCompare(b[0].toLowerCase()) || a[0].localeCompare(b[0]))
  .forEach(([name, file]) => out.push(`| \`${name}\` | \`${file}\` |`));
out.push('');

fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs', 'CODE_INDEX.md'), out.join('\n'));
console.log(`Wrote docs/CODE_INDEX.md (${scripts.length} scripts); refreshed ${refreshed} file headers.`);
